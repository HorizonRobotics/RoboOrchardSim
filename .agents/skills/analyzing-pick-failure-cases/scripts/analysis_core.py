def _distribution(
    records: Sequence[Mapping[str, Any]],
    field: str,
    *,
    analyzed_failure_count: int,
    all_failure_count: int,
) -> dict[str, Any]:
    seeds = defaultdict(list)
    for record in records:
        seeds[record["attribution"][field]].append(record["seed"])
    return {
        label: {
            "count": len(label_seeds),
            "seeds": sorted(label_seeds),
            "analyzed_failure_rate": (
                len(label_seeds) / analyzed_failure_count
                if analyzed_failure_count
                else 0.0
            ),
            "all_failure_rate": (
                len(label_seeds) / all_failure_count
                if all_failure_count
                else 0.0
            ),
        }
        for label, label_seeds in sorted(seeds.items())
    }


def _cross_tab(
    records: Sequence[Mapping[str, Any]],
    row_value,
    column_value,
) -> dict[str, Any]:
    cells = defaultdict(lambda: defaultdict(list))
    for record in records:
        cells[str(row_value(record))][str(column_value(record))].append(
            record["seed"]
        )
    return {
        row: {
            column: {"count": len(seeds), "seeds": sorted(seeds)}
            for column, seeds in sorted(columns.items())
        }
        for row, columns in sorted(cells.items())
    }


def _boolean_label(value: Any) -> str:
    if value is True:
        return "TRUE"
    if value is False:
        return "FALSE"
    return "N/A"


def _progress_bin(value: Any) -> str:
    if not isinstance(value, (int, float)):
        return "N/A"
    if value <= 0:
        return "0"
    if value < 0.5:
        return "(0,0.5)"
    if value < 1:
        return "[0.5,1)"
    return "1"


def aggregate_analyses(
    *,
    eval_result: Mapping[str, Any],
    analyses: Sequence[Mapping[str, Any]],
    validation_results: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    episodes = [
        dict(item)
        for item in eval_result.get("episode_results", [])
        if isinstance(item, Mapping)
    ]
    episodes_by_seed = {
        episode.get("seed"): episode
        for episode in episodes
        if episode.get("seed") is not None
    }
    for record in analyses:
        episode = episodes_by_seed.get(record.get("seed"))
        evaluation = record.get("evaluation")
        if episode is None or not isinstance(evaluation, Mapping):
            continue
        for field in ("success", "progress", "steps", "stop_reason"):
            if field in evaluation:
                episode[field] = evaluation[field]
        criteria_reached = {
            "reach_pick": evaluation.get("reach_pick"),
            "lift_pick": evaluation.get("lift_pick"),
        }
        metrics = dict(episode.get("metrics", {}))
        metrics["criteria_reached"] = criteria_reached
        episode["metrics"] = metrics
    failures = [item for item in episodes if item.get("success") is False]
    successes = [item for item in episodes if item.get("success") is True]
    failure_records = [
        record
        for record in analyses
        if record.get("evaluation", {}).get("success") is not True
    ]
    success_controls = [
        record
        for record in analyses
        if record.get("evaluation", {}).get("success") is True
    ]
    analyzed_failure_count = len(failure_records)
    all_failure_count = len(failures)

    overview_metrics = [extract_evaluation_metrics(item) for item in episodes]
    reach_count = sum(
        metric["reach_pick"] is True for metric in overview_metrics
    )
    lift_count = sum(
        metric["lift_pick"] is True for metric in overview_metrics
    )
    progresses = [
        metric["progress"]
        for metric in overview_metrics
        if isinstance(metric["progress"], (int, float))
    ]
    steps = [
        metric["steps"]
        for metric in overview_metrics
        if isinstance(metric["steps"], (int, float))
    ]
    stop_reasons = Counter(
        metric["stop_reason"] for metric in overview_metrics
    )

    unknown_seeds = sorted(
        record["seed"]
        for record in failure_records
        if "UNKNOWN" in record["attribution"].values()
        or "UNCERTAIN" in record["attribution"].values()
    )
    invalid_seeds = sorted(
        result.get("seed")
        for result in validation_results
        if not result.get("valid", True) and result.get("seed") is not None
    )
    fields = [
        "target_selection",
        "gripper_action",
        "target_interaction",
        "object_outcome",
        "cause",
    ]
    distributions = {
        field: _distribution(
            failure_records,
            field,
            analyzed_failure_count=analyzed_failure_count,
            all_failure_count=all_failure_count,
        )
        for field in fields
    }
    chain_seeds = defaultdict(list)
    for record in failure_records:
        attribution = record["attribution"]
        chain = " → ".join(
            attribution[field]
            for field in (
                "target_selection",
                "gripper_action",
                "target_interaction",
                "object_outcome",
            )
        )
        chain_seeds[chain].append(record["seed"])
    top_chains = [
        {
            "chain": chain,
            "count": len(seeds_for_chain),
            "seeds": sorted(seeds_for_chain),
        }
        for chain, seeds_for_chain in sorted(
            chain_seeds.items(), key=lambda item: (-len(item[1]), item[0])
        )
    ]
    cross_analysis = {
        "target_selection_by_reach_pick": _cross_tab(
            failure_records,
            lambda record: record["attribution"]["target_selection"],
            lambda record: _boolean_label(
                record.get("evaluation", {}).get("reach_pick")
            ),
        ),
        "gripper_action_by_target_interaction": _cross_tab(
            failure_records,
            lambda record: record["attribution"]["gripper_action"],
            lambda record: record["attribution"]["target_interaction"],
        ),
        "target_interaction_by_object_outcome": _cross_tab(
            failure_records,
            lambda record: record["attribution"]["target_interaction"],
            lambda record: record["attribution"]["object_outcome"],
        ),
        "cause_by_target_category": _cross_tab(
            failure_records,
            lambda record: record["attribution"]["cause"],
            lambda record: record.get("target", {}).get("category", "N/A"),
        ),
        "cause_by_progress": _cross_tab(
            failure_records,
            lambda record: record["attribution"]["cause"],
            lambda record: _progress_bin(
                record.get("evaluation", {}).get("progress")
            ),
        ),
    }
    return {
        "provenance_warning": PROVENANCE_WARNING,
        "evaluation": {
            "total": len(episodes),
            "success": len(successes),
            "failure": all_failure_count,
            "success_rate": len(successes) / len(episodes)
            if episodes
            else 0.0,
            "reach_pick": reach_count,
            "lift_pick": lift_count,
            "average_progress": sum(progresses) / len(progresses)
            if progresses
            else None,
            "average_steps": sum(steps) / len(steps) if steps else None,
            "stop_reasons": dict(
                sorted(stop_reasons.items(), key=lambda item: str(item[0]))
            ),
        },
        "coverage": {
            "analyzed_failures": analyzed_failure_count,
            "all_failures": all_failure_count,
            "analysis_rate": analyzed_failure_count / all_failure_count
            if all_failure_count
            else 0.0,
            "unanalyzed_failures": max(
                0, all_failure_count - analyzed_failure_count
            ),
            "unknown_or_uncertain_seeds": unknown_seeds,
            "validation_error_seeds": invalid_seeds,
        },
        "attribution": distributions,
        "top_chains": top_chains,
        "cross_analysis": cross_analysis,
        "success_controls": {
            "count": len(success_controls),
            "seeds": sorted(record["seed"] for record in success_controls),
        },
    }


