def _draw_annotations(
    draw: ImageDraw.ImageDraw,
    annotations: Sequence[Mapping[str, Any]],
    *,
    origin: tuple[int, int],
    size: tuple[int, int],
) -> None:
    origin_x, origin_y = origin
    width, height = size
    for raw in annotations:
        annotation = normalize_annotation(raw)
        geometry = annotation.get("geometry", [])
        color = tuple(annotation.get("color", [30, 205, 220]))
        if annotation.get("kind") == "box" and len(geometry) == 4:
            box = (
                origin_x + int(geometry[0] * width),
                origin_y + int(geometry[1] * height),
                origin_x + int(geometry[2] * width),
                origin_y + int(geometry[3] * height),
            )
            draw.rectangle(box, outline=color, width=5)
            if annotation.get("text"):
                text = str(annotation["text"])
                font = _font(19, bold=True)
                text_box = draw.textbbox((0, 0), text, font=font)
                label_width = text_box[2] - text_box[0] + 16
                label_height = text_box[3] - text_box[1] + 10
                label_y = max(2, box[1] - label_height)
                draw.rounded_rectangle(
                    (
                        box[0],
                        label_y,
                        box[0] + label_width,
                        label_y + label_height,
                    ),
                    radius=5,
                    fill=color,
                )
                draw.text(
                    (box[0] + 8, label_y + 2),
                    text,
                    font=font,
                    fill=(255, 255, 255),
                )


def _draw_metric_line(
    draw: ImageDraw.ImageDraw,
    evaluation: Mapping[str, Any],
    start: tuple[int, int],
) -> None:
    fields = [
        ("SUCCESS", "success"),
        ("PROGRESS", "progress"),
        ("REACH_PICK", "reach_pick"),
        ("LIFT_PICK", "lift_pick"),
        ("STEPS", "steps"),
        ("STOP", "stop_reason"),
    ]
    font = _font(18)
    x, y = start
    for index, (label, key) in enumerate(fields):
        value = evaluation.get(key)
        text = f"{label}={_format_metric_value(value)}"
        if value is True:
            color = (30, 165, 96)
        elif value is False:
            color = (220, 55, 55)
        elif value is None:
            color = (110, 118, 128)
        elif key == "stop_reason":
            color = (235, 132, 32)
        else:
            color = (225, 228, 234)
        draw.text((x, y), text, font=font, fill=color)
        text_box = draw.textbbox((0, 0), text, font=font)
        x += text_box[2] - text_box[0]
        if index != len(fields) - 1:
            separator = " | "
            draw.text((x, y), separator, font=font, fill=(150, 158, 170))
            separator_box = draw.textbbox((0, 0), separator, font=font)
            x += separator_box[2] - separator_box[0]


