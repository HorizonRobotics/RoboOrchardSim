class AnalysisError(RuntimeError):
    """Raised when deterministic pick-failure preparation cannot continue."""


def load_eval_result(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as stream:
        data = json.load(stream)
    if not isinstance(data, dict) or not isinstance(
        data.get("episode_results"), list
    ):
        raise AnalysisError(f"Invalid eval_result.json: {path}")
    return data


def select_episode_results(
    data: Mapping[str, Any],
    *,
    seeds: Sequence[int] | None,
    all_failures: bool,
    include_success: bool,
) -> list[dict[str, Any]]:
    if bool(seeds) == bool(all_failures):
        raise ValueError(
            "Select exactly one of explicit seeds or all_failures"
        )

    episode_results = data.get("episode_results")
    if not isinstance(episode_results, list):
        raise AnalysisError("eval_result.json has no episode_results list")
    by_seed = {
        int(item["seed"]): dict(item)
        for item in episode_results
        if isinstance(item, Mapping) and item.get("seed") is not None
    }
    if seeds:
        missing = [seed for seed in seeds if seed not in by_seed]
        if missing:
            raise AnalysisError(
                f"Seeds missing from eval_result.json: {missing}"
            )
        return [by_seed[seed] for seed in seeds]

    failures = [
        dict(item)
        for item in episode_results
        if isinstance(item, Mapping) and item.get("success") is False
    ]
    if not include_success:
        return failures
    controls = [
        dict(item)
        for item in episode_results
        if isinstance(item, Mapping) and item.get("success") is True
    ]
    return failures + controls


def extract_evaluation_metrics(
    episode_result: Mapping[str, Any],
) -> dict[str, Any]:
    metrics = episode_result.get("metrics")
    criteria_reached = None
    if isinstance(metrics, Mapping):
        candidate = metrics.get("criteria_reached")
        if isinstance(candidate, Mapping):
            criteria_reached = candidate
    return {
        "success": episode_result.get("success"),
        "progress": episode_result.get("progress"),
        "reach_pick": (
            criteria_reached.get("reach_pick") if criteria_reached else None
        ),
        "lift_pick": (
            criteria_reached.get("lift_pick") if criteria_reached else None
        ),
        "steps": episode_result.get("steps"),
        "stop_reason": episode_result.get("stop_reason"),
    }


def reconcile_evaluation_metrics(
    evaluation: Mapping[str, Any],
    metadata: Mapping[str, Any],
) -> dict[str, Any]:
    result = dict(evaluation)
    raw_progress = metadata.get("task_progress")
    task_progress = (
        float(raw_progress) if isinstance(raw_progress, (int, float)) else None
    )
    raw_success = metadata.get("task_success")
    task_success = (
        bool(raw_success)
        if isinstance(raw_success, (bool, int, float))
        else None
    )
    completed = task_progress is not None and task_progress >= 1.0
    overrode = completed and any(
        (
            result.get("success") is not True,
            result.get("progress") != 1.0,
            result.get("reach_pick") is not True,
            result.get("lift_pick") is not True,
            result.get("stop_reason") != "success",
        )
    )
    if completed:
        result.update(
            {
                "success": True,
                "progress": 1.0,
                "reach_pick": True,
                "lift_pick": True,
                "stop_reason": "success",
                "source": "MCAP_TASK_PROGRESS",
            }
        )
    else:
        result["source"] = "EVAL_RESULT"
    result["mcap_task_progress"] = task_progress
    result["mcap_task_success"] = task_success
    result["overrode_external_result"] = overrode
    return result


def discover_mcap(eval_root: Path, seed: int) -> Path:
    matches = sorted(
        path
        for path in eval_root.rglob("*.mcap")
        if f"seed_{seed}" in path.as_posix()
    )
    if not matches:
        raise AnalysisError(f"No MCAP found for seed {seed}")
    if len(matches) > 1:
        raise AnalysisError(
            f"Multiple MCAP files found for seed {seed}: {matches}"
        )
    return matches[0]


def nearest_timestamp_index(timestamps: Sequence[int], target: int) -> int:
    if not timestamps:
        raise ValueError("timestamps must not be empty")
    insertion = bisect.bisect_left(timestamps, target)
    if insertion == 0:
        return 0
    if insertion == len(timestamps):
        return len(timestamps) - 1
    before = timestamps[insertion - 1]
    after = timestamps[insertion]
    if target - before < after - target:
        return insertion - 1
    return insertion


def detect_close_intervals(
    samples: Sequence[tuple[int, float]],
    *,
    minimum_delta: float = 0.3,
    closed_threshold: float = 0.6,
    minimum_samples: int = 2,
) -> list[dict[str, Any]]:
    if minimum_samples < 1:
        raise ValueError("minimum_samples must be positive")
    if not samples:
        return []

    intervals = []
    baseline_index = 0
    baseline = float(samples[0][1])
    candidate_start = None
    closed_count = 0
    peak = baseline
    armed = True
    reopen_threshold = closed_threshold - minimum_delta / 2

    for index, (_, raw_position) in enumerate(samples):
        position = float(raw_position)
        if not armed:
            if position < reopen_threshold:
                armed = True
                baseline = position
                baseline_index = index
            continue

        if candidate_start is None and position < baseline:
            baseline = position
            baseline_index = index

        if candidate_start is None and position - baseline >= minimum_delta:
            candidate_start = min(index - 1, baseline_index + 1)
            candidate_start = max(0, candidate_start)
            peak = position

        if candidate_start is None:
            continue

        peak = max(peak, position)
        if position >= closed_threshold:
            closed_count += 1
        else:
            closed_count = 0

        if closed_count >= minimum_samples:
            intervals.append(
                {
                    "start_index": candidate_start,
                    "end_index": index,
                    "peak_position": round(peak, 6),
                }
            )
            candidate_start = None
            closed_count = 0
            armed = False

    return intervals


def summarize_gripper_trace(
    samples: Sequence[tuple[int, float]],
    *,
    minimum_delta: float = 0.3,
    closed_threshold: float = 0.6,
    minimum_samples: int = 2,
) -> dict[str, Any]:
    if not samples:
        return {
            "status": "UNKNOWN",
            "samples": [],
            "close_intervals": [],
        }
    intervals = detect_close_intervals(
        samples,
        minimum_delta=minimum_delta,
        closed_threshold=closed_threshold,
        minimum_samples=minimum_samples,
    )
    return {
        "status": "AVAILABLE",
        "samples": [
            {"timestamp_ns": timestamp, "position": position}
            for timestamp, position in samples
        ],
        "close_intervals": intervals,
        "thresholds": {
            "minimum_delta": minimum_delta,
            "closed_threshold": closed_threshold,
            "minimum_samples": minimum_samples,
        },
    }


def _extract_target(metadata: Mapping[str, Any]) -> dict[str, Any]:
    actors = metadata.get("actors")
    if not isinstance(actors, Mapping):
        return {}
    candidates = []
    for actor_path, actor in actors.items():
        if isinstance(actor, Mapping) and actor.get("actor_type") == "pick":
            candidates.append((actor_path, actor))
    if len(candidates) != 1:
        return {}
    actor_path, actor = candidates[0]
    initial_positions = metadata.get("init_position")
    final_positions = metadata.get("final_position")
    return {
        "actor_path": actor_path,
        "category": actor.get("actor_category"),
        "uuid": actor.get("actor_uuid"),
        "actor_type": actor.get("actor_type"),
        "initial_pose": (
            initial_positions.get(actor_path)
            if isinstance(initial_positions, Mapping)
            else None
        ),
        "final_pose": (
            final_positions.get(actor_path)
            if isinstance(final_positions, Mapping)
            else None
        ),
    }


def _joint_position(decoded: Any, joint_name: str) -> float | None:
    for state in decoded.states:
        if state.name == joint_name:
            return float(state.position)
    return None


def _quaternion_rotation_matrix(
    quaternion_xyzw: Sequence[float],
) -> list[list[float]]:
    x, y, z, w = [float(value) for value in quaternion_xyzw]
    norm = math.sqrt(x * x + y * y + z * z + w * w)
    if norm == 0:
        raise ValueError("camera quaternion must be non-zero")
    x, y, z, w = [value / norm for value in (x, y, z, w)]
    return [
        [
            1 - 2 * (y * y + z * z),
            2 * (x * y - z * w),
            2 * (x * z + y * w),
        ],
        [
            2 * (x * y + z * w),
            1 - 2 * (x * x + z * z),
            2 * (y * z - x * w),
        ],
        [
            2 * (x * z - y * w),
            2 * (y * z + x * w),
            1 - 2 * (x * x + y * y),
        ],
    ]


def project_point_to_image(
    *,
    point: Sequence[float],
    camera_translation: Sequence[float],
    camera_quaternion_xyzw: Sequence[float],
    intrinsic_matrix: Sequence[float],
    image_size: tuple[int, int],
) -> dict[str, Any] | None:
    if len(point) < 3 or len(intrinsic_matrix) != 9:
        raise ValueError("point and intrinsic matrix have invalid dimensions")
    rotation = _quaternion_rotation_matrix(camera_quaternion_xyzw)
    delta = [
        float(point[index]) - float(camera_translation[index])
        for index in range(3)
    ]
    point_camera = [
        sum(rotation[row][column] * delta[row] for row in range(3))
        for column in range(3)
    ]
    if point_camera[2] <= 0:
        return None
    u = float(intrinsic_matrix[0]) * point_camera[0] / point_camera[2] + float(
        intrinsic_matrix[2]
    )
    v = float(intrinsic_matrix[4]) * point_camera[1] / point_camera[2] + float(
        intrinsic_matrix[5]
    )
    width, height = image_size
    return {
        "u": round(u, 6),
        "v": round(v, 6),
        "normalized": [round(u / width, 6), round(v / height, 6)],
    }


def extract_mcap_manifest(
    mcap_path: Path,
    *,
    minimum_delta: float = 0.3,
    closed_threshold: float = 0.6,
    minimum_samples: int = 2,
) -> dict[str, Any]:
    camera_frames = {
        view: {"indexes": [], "timestamps_ns": []} for view in CAMERA_TOPICS
    }
    camera_calibration = {}
    camera_transforms = {}
    metadata = {}
    actual_gripper_samples = []
    command_gripper_samples = []
    topics = (
        list(CAMERA_TOPICS.values())
        + list(CAMERA_INFO_TOPICS.values())
        + list(CAMERA_TF_TOPICS.values())
        + [META_TOPIC, ROBOT_JOINT_TOPIC, GRIPPER_COMMAND_TOPIC]
    )
    with mcap_path.open("rb") as stream:
        reader = make_reader(stream, decoder_factories=[DecoderFactory()])
        for _, channel, message, decoded in reader.iter_decoded_messages(
            topics=topics
        ):
            topic = channel.topic
            if topic == META_TOPIC:
                metadata = MessageToDict(
                    decoded, preserving_proto_field_name=True
                )
                continue
            if topic == ROBOT_JOINT_TOPIC:
                position = _joint_position(decoded, "panda_joint8")
                if position is not None:
                    actual_gripper_samples.append((message.log_time, position))
                continue
            if topic == GRIPPER_COMMAND_TOPIC:
                position = _joint_position(decoded, "joint1")
                if position is not None:
                    command_gripper_samples.append(
                        (message.log_time, position)
                    )
                continue
            for view, info_topic in CAMERA_INFO_TOPICS.items():
                if topic == info_topic and view not in camera_calibration:
                    camera_calibration[view] = {
                        "width": int(decoded.width),
                        "height": int(decoded.height),
                        "K": [float(value) for value in decoded.K],
                    }
                    break
            else:
                for view, tf_topic in CAMERA_TF_TOPICS.items():
                    if topic == tf_topic and view not in camera_transforms:
                        camera_transforms[view] = {
                            "translation": [
                                float(decoded.translation.x),
                                float(decoded.translation.y),
                                float(decoded.translation.z),
                            ],
                            "quaternion_xyzw": [
                                float(decoded.rotation.x),
                                float(decoded.rotation.y),
                                float(decoded.rotation.z),
                                float(decoded.rotation.w),
                            ],
                        }
                        break
            for view, camera_topic in CAMERA_TOPICS.items():
                if topic == camera_topic:
                    frame = camera_frames[view]
                    frame["indexes"].append(len(frame["indexes"]))
                    frame["timestamps_ns"].append(message.log_time)
                    break

    gripper = summarize_gripper_trace(
        actual_gripper_samples,
        minimum_delta=minimum_delta,
        closed_threshold=closed_threshold,
        minimum_samples=minimum_samples,
    )
    gripper["joint"] = "panda_joint8"
    gripper["topic"] = ROBOT_JOINT_TOPIC
    gripper["command_samples"] = [
        {"timestamp_ns": timestamp, "position": position}
        for timestamp, position in command_gripper_samples
    ]
    warnings = []
    for view, frame in camera_frames.items():
        if not frame["indexes"]:
            warnings.append(f"Missing RGB topic for view {view}")
    if not metadata:
        warnings.append("Missing /meta_data")
    if gripper["status"] == "UNKNOWN":
        warnings.append("Missing panda_joint8 actual gripper trace")
    target = _extract_target(metadata)
    target_projections = {}
    initial_pose = target.get("initial_pose")
    if isinstance(initial_pose, Sequence) and len(initial_pose) >= 3:
        for view in CAMERA_TOPICS:
            calibration = camera_calibration.get(view)
            transform = camera_transforms.get(view)
            if not calibration or not transform:
                continue
            target_projections[view] = project_point_to_image(
                point=initial_pose[:3],
                camera_translation=transform["translation"],
                camera_quaternion_xyzw=transform["quaternion_xyzw"],
                intrinsic_matrix=calibration["K"],
                image_size=(calibration["width"], calibration["height"]),
            )
    return {
        "source_mcap": str(mcap_path),
        "instruction": metadata.get("instruction"),
        "target": target,
        "initial_target_projection_proposals": {
            "status": "UNVERIFIED",
            "views": target_projections,
            "warning": (
                "Coordinate-frame conventions may differ. Visually verify "
                "every proposal before rendering a target marker."
            ),
        },
        "camera_calibration": camera_calibration,
        "initial_camera_transforms": camera_transforms,
        "metadata": metadata,
        "mcap_evaluation": {
            "task_success": metadata.get("task_success"),
            "task_progress": metadata.get("task_progress"),
        },
        "camera_frames": camera_frames,
        "gripper": gripper,
        "warnings": warnings,
    }


def extract_frame_at_index(
    mcap_path: Path,
    view: str,
    frame_index: int,
) -> Image.Image:
    if view not in CAMERA_TOPICS:
        raise ValueError(f"Unknown camera view: {view}")
    if frame_index < 0:
        raise ValueError("frame_index must be non-negative")
    topic = CAMERA_TOPICS[view]
    with mcap_path.open("rb") as stream:
        reader = make_reader(stream, decoder_factories=[DecoderFactory()])
        for index, (_, _, _, decoded) in enumerate(
            reader.iter_decoded_messages(topics=[topic])
        ):
            if index == frame_index:
                return Image.open(io.BytesIO(decoded.data)).convert("RGB")
    raise AnalysisError(
        f"Frame {frame_index} unavailable for {view} in {mcap_path}"
    )


def extract_frames_at_indexes(
    mcap_path: Path,
    view: str,
    frame_indexes: Sequence[int],
) -> dict[int, Image.Image]:
    requested = sorted(set(frame_indexes))
    if not requested:
        return {}
    remaining = set(requested)
    images = {}
    topic = CAMERA_TOPICS[view]
    with mcap_path.open("rb") as stream:
        reader = make_reader(stream, decoder_factories=[DecoderFactory()])
        for index, (_, _, _, decoded) in enumerate(
            reader.iter_decoded_messages(topics=[topic])
        ):
            if index not in remaining:
                continue
            images[index] = Image.open(io.BytesIO(decoded.data)).convert("RGB")
            remaining.remove(index)
            if not remaining:
                break
    if remaining:
        raise AnalysisError(
            f"Frames {sorted(remaining)} unavailable for {view} in {mcap_path}"
        )
    return images


def _font(size: int, *, bold: bool = False) -> ImageFont.ImageFont:
    candidates = [
        (
            "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
            if bold
            else "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
        ),
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
        if bold
        else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).is_file():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default()


def render_candidate_sheet(
    *,
    frames: Sequence[tuple[int, Image.Image]],
    view: str,
    output_path: Path,
    columns: int = 4,
) -> dict[str, Any]:
    ordered = sorted(frames, key=lambda item: item[0])
    tile_width = 320
    tile_height = 205
    rows = max(1, math.ceil(len(ordered) / columns))
    canvas = Image.new(
        "RGB", (columns * tile_width, rows * tile_height), (18, 21, 26)
    )
    draw = ImageDraw.Draw(canvas)
    label_font = _font(18, bold=True)
    for cell, (frame_index, image) in enumerate(ordered):
        x = cell % columns * tile_width
        y = cell // columns * tile_height
        thumbnail = image.copy()
        thumbnail.thumbnail(
            (tile_width, tile_height - 30), Image.Resampling.LANCZOS
        )
        canvas.paste(thumbnail, (x, y + 30))
        draw.text(
            (x + 8, y + 4),
            f"{view}  frame={frame_index}",
            font=label_font,
            fill=(245, 223, 85),
        )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(output_path, quality=92)
    return {
        "path": str(output_path),
        "view": view,
        "frame_indexes": [item[0] for item in ordered],
    }


def normalize_annotation(annotation: Mapping[str, Any]) -> dict[str, Any]:
    result = dict(annotation)
    geometry = annotation.get("geometry", [])
    if not isinstance(geometry, Sequence):
        raise ValueError("annotation geometry must be a sequence")
    result["geometry"] = [
        min(1.0, max(0.0, float(value))) for value in geometry
    ]
    return result


def _required_mapping(
    value: Any, name: str, errors: list[str]
) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        errors.append(f"{name} must be an object")
        return {}
    return value


def validate_analysis(
    analysis: Mapping[str, Any],
    extracted_signals: Mapping[str, Any],
) -> dict[str, Any]:
    errors = []
    warnings = []
    required = {
        "schema_version",
        "seed",
        "instruction",
        "target",
        "evidence_window",
        "attribution",
        "evidence",
        "evaluation",
        "provenance",
    }
    for field in sorted(required - analysis.keys()):
        errors.append(f"Missing required field: {field}")

    window = _required_mapping(
        analysis.get("evidence_window"), "evidence_window", errors
    )
    frames = window.get("frames")
    if not isinstance(frames, list) or len(frames) != 4:
        errors.append(
            "evidence_window.frames must contain exactly four frames"
        )
        frames = []
    elif frames != sorted(frames) or len(set(frames)) != 4:
        errors.append("Evidence frames must be strictly chronological")

    camera_frames = extracted_signals.get("camera_frames")
    if isinstance(camera_frames, Mapping):
        for view in window.get("views", []):
            view_frames = camera_frames.get(view)
            indexes = (
                view_frames.get("indexes", [])
                if isinstance(view_frames, Mapping)
                else []
            )
            unresolved = [frame for frame in frames if frame not in indexes]
            if unresolved:
                errors.append(f"Unresolved {view} frame indexes: {unresolved}")

    attribution = _required_mapping(
        analysis.get("attribution"), "attribution", errors
    )
    enums = {
        "target_selection": TARGET_SELECTION_VALUES,
        "gripper_action": GRIPPER_ACTION_VALUES,
        "target_interaction": TARGET_INTERACTION_VALUES,
        "object_outcome": OBJECT_OUTCOME_VALUES,
        "cause": CAUSE_VALUES,
    }
    for field, allowed in enums.items():
        value = attribution.get(field)
        if value not in allowed:
            errors.append(f"Invalid {field}: {value}")

    if all(
        attribution.get(field) in allowed for field, allowed in enums.items()
    ):
        errors.extend(
            _cause_consistency_errors(
                attribution,
                analysis.get("evaluation", {}),
            )
        )

    evidence = _required_mapping(analysis.get("evidence"), "evidence", errors)
    if not evidence.get("summary"):
        errors.append("evidence.summary is required")
    interaction_frames = evidence.get("interaction_visible_frames", [])
    if (
        attribution.get("target_interaction") != "UNKNOWN"
        and not interaction_frames
    ):
        errors.append(
            "Definite target interaction requires interaction frames"
        )

    target = extracted_signals.get("target")
    if (
        attribution.get("target_selection") in {"CORRECT", "WRONG_OBJECT"}
        and not target
    ):
        errors.append("Definite target selection requires target metadata")
    if attribution.get("target_selection") == "WRONG_OBJECT":
        if not evidence.get("target_visible_frames"):
            errors.append("WRONG_OBJECT requires target_visible_frames")
        distractor_frames = evidence.get(
            "distractor_interaction_frames", interaction_frames
        )
        if not distractor_frames:
            errors.append(
                "WRONG_OBJECT requires distractor interaction evidence"
            )

    metadata = extracted_signals.get("metadata")
    task_progress = (
        metadata.get("task_progress")
        if isinstance(metadata, Mapping)
        else None
    )
    evaluation = analysis.get("evaluation")
    if (
        isinstance(task_progress, (int, float))
        and task_progress >= 1.0
        and (
            not isinstance(evaluation, Mapping)
            or evaluation.get("success") is not True
        )
    ):
        errors.append(
            "MCAP task_progress=1.0 requires evaluation.success=true"
        )

    outcome = attribution.get("object_outcome")
    if (
        outcome
        in {
            "PUSHED_AWAY",
            "LIFTED_SUCCESSFULLY",
            "LIFTED_THEN_DROPPED",
            "LIFTED_INSUFFICIENTLY",
        }
        and len(evidence.get("outcome_frames", [])) < 2
    ):
        errors.append(f"{outcome} requires a continuous outcome sequence")

    gripper = extracted_signals.get("gripper")
    if isinstance(gripper, Mapping):
        status = gripper.get("status")
        close_intervals = gripper.get("close_intervals", [])
        action = attribution.get("gripper_action")
        if status == "UNKNOWN" and action != "UNKNOWN":
            errors.append(
                "Definite gripper action conflicts with missing trace"
            )
        if (
            status == "AVAILABLE"
            and action == "CLOSE_ATTEMPTED"
            and not close_intervals
        ):
            errors.append("CLOSE_ATTEMPTED conflicts with the available trace")
        if (
            status == "AVAILABLE"
            and action == "NO_CLOSE_ATTEMPT"
            and close_intervals
        ):
            errors.append(
                "NO_CLOSE_ATTEMPT conflicts with the available trace"
            )
    else:
        warnings.append("No gripper summary available")

    return {"valid": not errors, "errors": errors, "warnings": warnings}


def _cause_consistency_errors(
    attribution: Mapping[str, Any],
    evaluation: Any,
) -> list[str]:
    cause = attribution["cause"]
    requirements = {
        "SELECTED_DISTRACTOR": {
            "target_selection": "WRONG_OBJECT",
        },
        "OFF_TARGET_APPROACH": {
            "target_selection": "CORRECT",
            "target_interaction": "NO_CONTACT",
        },
        "NO_CLOSE_ATTEMPT": {
            "target_selection": "CORRECT",
            "gripper_action": "NO_CLOSE_ATTEMPT",
            "target_interaction": "CONTACT_NO_GRASP",
        },
        "MISALIGNED_GRASP": {
            "target_selection": "CORRECT",
            "gripper_action": "CLOSE_ATTEMPTED",
            "target_interaction": "CONTACT_NO_GRASP",
        },
        "UNSTABLE_GRASP": {
            "target_selection": "CORRECT",
            "gripper_action": "CLOSE_ATTEMPTED",
            "target_interaction": "TRANSIENT_GRASP",
        },
        "PREMATURE_GRIPPER_OPENING": {
            "target_selection": "CORRECT",
            "gripper_action": "CLOSE_ATTEMPTED",
            "target_interaction": "TRANSIENT_GRASP",
        },
        "INSUFFICIENT_LIFT_MOTION": {
            "target_selection": "CORRECT",
            "gripper_action": "CLOSE_ATTEMPTED",
            "target_interaction": "STABLE_GRASP",
            "object_outcome": "LIFTED_INSUFFICIENTLY",
        },
    }
    errors = []
    for field, expected in requirements.get(cause, {}).items():
        actual = attribution.get(field)
        if actual != expected:
            errors.append(
                f"Cause {cause} requires {field}={expected}; got {actual}"
            )

    success = (
        evaluation.get("success") if isinstance(evaluation, Mapping) else None
    )
    if cause == "NONE" and success is not True:
        errors.append("Cause NONE requires evaluation.success=true")
    elif success is True and cause != "NONE":
        errors.append(
            f"Cause {cause} conflicts with evaluation.success=true; use NONE"
        )
    return errors


def _format_metric_value(value: Any) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value).upper()


def format_metric_line(evaluation: Mapping[str, Any]) -> str:
    fields = [
        ("SUCCESS", "success"),
        ("PROGRESS", "progress"),
        ("REACH_PICK", "reach_pick"),
        ("LIFT_PICK", "lift_pick"),
        ("STEPS", "steps"),
        ("STOP", "stop_reason"),
    ]
    return " | ".join(
        f"{label}={_format_metric_value(evaluation.get(key))}"
        for label, key in fields
    )


